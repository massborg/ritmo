// Turns the shoe drawings in assets/shoes/*.svg into src/components/shoe-shapes.ts, so the app can draw them
// inline and colour each part. Run: node scripts/shoe-shapes.cjs
const fs = require('fs'); const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'shoes');
const out = {};
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.svg')).sort()) {
  const svg = fs.readFileSync(path.join(dir, f), 'utf8');
  if (/<script|href=|<image|foreignObject|\son[a-z]+=/i.test(svg)) throw new Error(`${f}: unexpected content`);
  const parts = [...svg.matchAll(/<path class="([a-z]+)" d="([^"]+)"\s*\/>/g)].map((m) => [m[1], m[2].replace(/\s+/g, ' ').trim()]).filter(([c]) => c !== 'ground');
  out[f.replace(/^shoe-|\.svg$/g, '')] = parts;
}
const body = `// Generated by scripts/shoe-shapes.cjs from assets/shoes/*.svg. Do not edit by hand.
// Generic running-shoe shapes (no brand designs): [part, path] drawn in order on a 240 x 120 canvas.
export type ShoePart = 'outsole' | 'midsole' | 'upper' | 'accent' | 'detail' | 'seam';
export const SHOE_SHAPES = ${JSON.stringify(out, null, 0).replace(/\],\[/g, '],\n    [').replace(/":\[\[/g, '": [\n    [').replace(/\]\],"/g, ']],\n  "')} as const satisfies Record<string, readonly (readonly [ShoePart, string])[]>;
export type ShoeShape = keyof typeof SHOE_SHAPES;
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'components', 'shoe-shapes.ts'), body);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v.length}`).join(', '));
