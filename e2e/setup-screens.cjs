// Screenshots of each setup step and the photo editor (phone).
const { chromium, devices } = require('playwright');
const { createMock } = require('./mock-supabase.cjs');
const { signUpAndConfirm, PHOTO, SUPA } = require('./flows.cjs');
const fs = require('fs'); const path = require('path');
const OUT = process.env.OUT_DIR || path.join(__dirname, 'out', 'setup');
fs.mkdirSync(OUT, { recursive: true });
(async () => {
  if (!fs.existsSync(PHOTO)) require('child_process').execSync(`convert -size 900x700 gradient:'#E8480C'-'#1E1A17' ${PHOTO}`);
  const mock = createMock();
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'] });
  await ctx.addInitScript(() => { try { sessionStorage.setItem('ritmo:splash-shown', '1'); } catch { /* */ } });
  await mock.install(ctx, SUPA);
  const page = await ctx.newPage();
  const shot = async (n) => { await page.waitForTimeout(400); await page.screenshot({ path: path.join(OUT, `${n}.png`) }); console.log('saved', n); };
  const cont = () => page.getByRole('button', { name: 'Continue', exact: true }).click();
  await signUpAndConfirm(page, mock, 'shots@test.ritmo');
  await page.waitForURL(/setup/);
  await shot('1-consent');
  await page.locator('#c-health').check(); await cont();
  await page.locator('#s-name').fill('Sam');
  await page.getByLabel('Day', { exact: true }).selectOption('15'); await page.getByLabel('Month', { exact: true }).selectOption('4'); await page.getByLabel('Year', { exact: true }).selectOption('1990');
  await shot('2-basics');
  await page.getByRole('button', { name: 'Add a photo' }).click();
  await page.locator('input[type=file][accept^="image/jpeg"]').setInputFiles(PHOTO);
  await page.getByRole('button', { name: 'Save picture' }).waitFor();
  await shot('2b-photo-crop');
  await page.getByRole('button', { name: 'Save picture' }).click();
  await page.waitForTimeout(800);
  await cont();
  await page.getByRole('button', { name: 'Yes', exact: true }).nth(1).click();
  for (const i of [0, 2, 3, 4, 5]) await page.getByRole('button', { name: 'No', exact: true }).nth(i).click();
  await page.getByText('Please check with a doctor').scrollIntoViewIfNeeded();
  await shot('3-health-yes');
  await page.locator('#h-ack').check(); await cont();
  await page.getByRole('radio', { name: /new to running/ }).click();
  await shot('4-background');
  await page.locator('fieldset').filter({ hasText: 'Can you run for 10 minutes' }).getByRole('button', { name: 'Not yet' }).click();
  await page.locator('fieldset').filter({ hasText: 'Do you walk regularly' }).getByRole('button', { name: 'Yes' }).click();
  await cont();
  await page.getByRole('radio', { name: 'My first 10K' }).click(); await cont();
  await shot('5-goal-safer');
  await page.getByRole('button', { name: 'Run 5K without stopping first' }).click();
  await shot('6-schedule');
  await cont();
  await shot('7-injuries');
  await page.getByRole('button', { name: /No injuries/ }).click();
  await shot('8-runs');
  await page.getByRole('button', { name: 'Skip for now' }).click();
  await shot('9-preview');
  await page.getByRole('button', { name: 'Start my plan' }).click();
  await page.waitForURL(/\/$/);
  await shot('10-today-with-photo');
  await page.goto(page.url().replace(/\/$/, '/coach'));
  await page.locator('#ask').fill('How am I doing?');
  await page.getByRole('button', { name: 'Send' }).click();
  await page.waitForTimeout(600);
  await shot('11-coach-after-declining-ai');
  await b.close();
})();
