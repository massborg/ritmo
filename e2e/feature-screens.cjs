// Screens of the newer features on the review-shaped account. Usage: OUT_DIR=... node e2e/feature-screens.cjs
const { chromium, devices } = require('playwright');
const { createMock } = require('./mock-supabase.cjs');
const { ryanRows } = require('./fixtures/ryan.cjs');
const fs = require('fs'); const path = require('path');
const APP = process.env.APP_URL || 'http://localhost:4173';
const OUT = process.env.OUT_DIR || path.join(__dirname, 'out', 'features');
const SUPA = 'https://gujuzacfqxbwfpprkgrx.supabase.co';
fs.mkdirSync(OUT, { recursive: true });
(async () => {
  const mock = createMock();
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'] });
  await ctx.addInitScript(() => { try { sessionStorage.setItem('ritmo:splash-shown', '1'); } catch { /* */ } });
  await mock.install(ctx, SUPA);
  const page = await ctx.newPage();
  const shot = async (n, full = false) => { await page.waitForTimeout(600); await page.screenshot({ path: path.join(OUT, `${n}.png`), fullPage: full }); console.log('saved', n); };
  const email = 'features@test.ritmo';
  await page.goto(`${APP}/signup`);
  await page.locator('#su-email').fill(email); await page.locator('#su-password').fill('Runner2026');
  for (const c of await page.locator('.consent input').all()) await c.check();
  await page.getByRole('button', { name: 'Create account' }).click(); await page.getByText('Check your email').waitFor();
  await page.goto(`${APP}/login?confirmed=1${mock.linkFor(email, 'signup')}`);
  await page.waitForURL(/setup/);
  const uid = mock.state.users.get(email).id;
  const rows = ryanRows(uid, new Date());
  rows.profiles[0].data.profile.training = { strengthPerWeek: 1 };
  rows.profiles[0].data.profile.daysAvailable = [0, 1, 3, 4, 5, 6];
  for (const t of Object.keys(rows)) mock.state.tables[t].push(...rows[t]);
  await page.evaluate(() => indexedDB.deleteDatabase('keyval-store'));
  await page.goto(`${APP}/`); await page.waitForTimeout(1200);
  for (const name of [/Build my plan/, /Train \d days a week/, /Start my plan/]) { const x = page.getByRole('button', { name }).first(); if (await x.isVisible().catch(() => false)) { await x.click(); await page.waitForTimeout(900); } }
  await page.goto(`${APP}/`); await page.waitForTimeout(900);
  await page.getByRole('button', { name: /^Add a run/ }).click(); await shot('1-plus-menu');
  await page.getByText('Not feeling 100%', { exact: true }).click(); await shot('2-not-feeling');
  await page.keyboard.press('Escape');
  await page.waitForTimeout(1600);
  const planRow = mock.state.tables.plans[mock.state.tables.plans.length - 1];
  const q = planRow.data.sessions.find((x) => x.type === 'threshold' && x.date > new Date().toISOString().slice(0, 10));
  await page.goto(`${APP}/session/${q.id}`); await shot('3-session-change', true);
  await page.goto(`${APP}/coach`);
  await page.locator('#ask').fill('Can you move Thursday to Friday?'); await page.getByRole('button', { name: 'Send' }).click(); await page.waitForTimeout(700);
  await shot('4-coach-proposal');
  await page.goto(`${APP}/goals`); await page.getByText('Training style').scrollIntoViewIfNeeded(); await shot('5-training-style');
  await page.goto(`${APP}/profile/shoes`); await page.getByRole('heading', { name: 'Shoes' }).first().scrollIntoViewIfNeeded(); await page.evaluate(() => window.scrollBy(0, -380)); await shot('6-progress-trends');
  await b.close();
})();
